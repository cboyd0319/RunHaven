//! Per-capability trust-boundary guards: main-read stays read-only, run-control
//! owns only the sensitive commands, launch stays isolated, and the session
//! input and diagnostics bridges stay narrow.

use std::fs;
use std::path::Path;

use super::support::{
    ATTENTION_BADGE_PERMISSION, MAIN_READ_FORBIDDEN_PERMISSIONS, MENU_STATE_PERMISSION,
    RUN_CONTROL_PERMISSIONS, assert_generated_permission_allows_only,
    assert_lacks_forbidden_host_markers, assert_same_permission_set, capability_permissions,
    capability_windows, manifest_dir, normalize, read_text,
};

#[test]
fn main_read_capability_stays_read_only() {
    let permissions = capability_permissions("main-read.json");
    for forbidden in MAIN_READ_FORBIDDEN_PERMISSIONS {
        assert!(
            !permissions.iter().any(|permission| permission == forbidden),
            "main-read must stay read-only and cannot grant {forbidden}"
        );
    }
    assert_lacks_forbidden_host_markers("main-read capability", &permissions.join("\n"));
}

#[test]
fn run_control_capability_stays_narrow_to_sensitive_commands() {
    let run_control_permissions = capability_permissions("run-control.json");
    let expected = RUN_CONTROL_PERMISSIONS
        .iter()
        .map(|(permission, _)| *permission)
        .collect::<Vec<_>>();
    assert_same_permission_set("run-control", &run_control_permissions, &expected);

    let main_read_permissions = capability_permissions("main-read.json");
    for (permission, command) in RUN_CONTROL_PERMISSIONS {
        assert!(
            !main_read_permissions
                .iter()
                .any(|candidate| candidate == permission),
            "main-read must stay read-only and cannot grant {permission}"
        );
        assert_generated_permission_allows_only(command);
    }
}

#[test]
fn launch_permission_stays_out_of_read_only_capability() {
    let manifest_dir = manifest_dir();
    let main_read = manifest_dir.join("capabilities").join("main-read.json");
    let launch_run = manifest_dir.join("capabilities").join("launch-run.json");
    let plan_permission = manifest_dir
        .join("permissions")
        .join("autogenerated")
        .join("plan_run.toml");

    let main_read_raw = fs::read_to_string(&main_read).expect("read main-read capability");
    assert!(
        !main_read_raw.contains("allow-launch-run"),
        "main-read must not grant launch_run"
    );

    let launch_run_raw = fs::read_to_string(&launch_run).expect("read launch-run capability");
    assert!(
        launch_run_raw.contains("\"permissions\": [\"allow-launch-run\"]"),
        "launch-run capability must grant only launch_run"
    );

    assert_generated_permission_allows_only("launch_run");

    let plan_permission_raw =
        fs::read_to_string(&plan_permission).expect("read plan_run permission");
    assert!(
        plan_permission_raw.contains("commands.allow = [\"plan_run\"]"),
        "plan_run permission must allow only the read-only planning command"
    );
}

#[test]
fn menu_events_capability_stays_listen_only() {
    // The menu bar is Rust-to-WebView dispatch only. The main window may
    // listen for menu ids but never gains emit, so the WebView cannot forge
    // events toward Rust or other windows.
    let permissions = capability_permissions("menu-events.json");
    assert_same_permission_set(
        "menu-events",
        &permissions,
        &["core:event:allow-listen", "core:event:allow-unlisten"],
    );
    assert!(
        !permissions
            .iter()
            .any(|permission| permission.contains("emit")),
        "menu-events must never grant event emission to the WebView"
    );
}

#[test]
fn window_chrome_capability_stays_drag_only() {
    // The overlay title bar's drag regions need exactly two user-gesture window
    // APIs: start a drag, and the internal toggle-maximize that Tauri's
    // drag-region script invokes on double-click (NOT the general
    // allow-toggle-maximize). Nothing that reads data, closes, resizes
    // programmatically, or reaches another window may ride along.
    let permissions = capability_permissions("window-chrome.json");
    assert_same_permission_set(
        "window-chrome",
        &permissions,
        &[
            "core:window:allow-start-dragging",
            "core:window:allow-internal-toggle-maximize",
        ],
    );
    assert_eq!(
        capability_windows("window-chrome.json"),
        vec!["main".to_string()],
        "window-chrome must stay main-window-only"
    );
}

#[test]
fn attention_badge_capability_stays_narrow() {
    // The Dock badge command is benign UI state, but it is still a mutation
    // the WebView can trigger, so it lives in its own one-permission
    // capability instead of widening main-read (read-only) or run-control
    // (session-sensitive).
    let permissions = capability_permissions("attention-badge.json");
    assert_same_permission_set(
        "attention-badge",
        &permissions,
        &[ATTENTION_BADGE_PERMISSION],
    );
    assert_generated_permission_allows_only("set_attention_badge");

    let main_read = capability_permissions("main-read.json");
    assert!(
        !main_read
            .iter()
            .any(|permission| permission == ATTENTION_BADGE_PERMISSION),
        "main-read must stay read-only and cannot grant the Dock badge command"
    );
    let run_control = capability_permissions("run-control.json");
    assert!(
        !run_control
            .iter()
            .any(|permission| permission == ATTENTION_BADGE_PERMISSION),
        "run-control must not own the isolated Dock badge command"
    );
}

