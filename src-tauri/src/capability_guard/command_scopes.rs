#[test]
fn session_input_registry_stays_off_dormant_codex_transports() {
    let manifest_dir = manifest_dir();
    let protected_files = [
        manifest_dir.join("Cargo.toml"),
        manifest_dir.join("src").join("session_input.rs"),
    ];
    let forbidden = [
        "codex-app-server",
        "codex-exec-server",
        "codex-file-system",
        "codex-core",
        "rmcp",
        "app_server",
        "exec_server",
        "filesystem_rpc",
        "mcp",
    ];

    for path in protected_files {
        let normalized = normalize(&read_text(&path));
        for item in forbidden {
            let normalized_item = item.replace('-', "_");
            assert!(
                !normalized.contains(&normalized_item),
                "{} pulls dormant Codex transport marker `{item}` into the GUI session input boundary",
                path.display()
            );
        }
    }
}

/// The window-scope pin for the whole capability set. Adding a capability that
/// reaches any other window label, or widening an existing one, fails here and
/// needs a security review first.
#[test]
fn every_capability_stays_main_window_only() {
    let dir = manifest_dir().join("capabilities");
    let mut checked = 0usize;
    for entry in fs::read_dir(&dir).expect("read capabilities directory") {
        let path = entry.expect("capabilities directory entry").path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("json") {
            continue;
        }
        let file_name = path
            .file_name()
            .and_then(|name| name.to_str())
            .expect("capability file name")
            .to_owned();
        let windows = capability_windows(&file_name);
        assert_eq!(
            windows,
            ["main"],
            "capability {file_name} must target exactly the main window; \
             changing a capability's window scope is a trust-boundary change"
        );
        checked += 1;
    }
    assert!(checked >= 9, "expected all capability files to be checked");
}

#[test]
fn managed_session_diagnostics_stays_read_only() {
    let manifest_dir = manifest_dir();
    let main_read = manifest_dir.join("capabilities").join("main-read.json");
    let run_control = manifest_dir.join("capabilities").join("run-control.json");
    let diagnostics_permission = manifest_dir
        .join("permissions")
        .join("autogenerated")
        .join("get_managed_session_diagnostics.toml");

    let main_read_raw = fs::read_to_string(&main_read).expect("read main-read capability");
    assert!(
        main_read_raw.contains("allow-get-managed-session-diagnostics"),
        "main-read must grant the fixed selected-session diagnostics command"
    );
    let run_control_raw = fs::read_to_string(&run_control).expect("read run-control capability");
    assert!(
        !run_control_raw.contains("allow-get-managed-session-diagnostics"),
        "run-control must not own read-only selected-session diagnostics"
    );
    let permission_raw = fs::read_to_string(&diagnostics_permission)
        .expect("read get_managed_session_diagnostics permission");
    assert!(
        permission_raw.contains("commands.allow = [\"get_managed_session_diagnostics\"]"),
        "get_managed_session_diagnostics permission must allow only the fixed command"
    );
}
